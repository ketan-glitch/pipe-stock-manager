-- Pipe Stock Manager: multi-item sales module
-- Run once in Supabase SQL Editor after the original schema.sql.

create table if not exists public.sales (
  id uuid primary key default gen_random_uuid(),
  sale_number bigint generated by default as identity unique,
  customer_name text not null check (length(trim(customer_name)) > 0),
  customer_phone text not null check (length(trim(customer_phone)) > 0),
  subtotal numeric(12,2) not null check (subtotal > 0),
  amount_received numeric(12,2) not null default 0 check (amount_received >= 0 and amount_received <= subtotal),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','partial','paid','cancelled')),
  status text not null default 'completed' check (status in ('completed','cancelled')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  cancelled_at timestamptz,
  cancelled_by uuid references auth.users(id) on delete set null
);

create table if not exists public.sale_payments (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  recorded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales(id) on delete restrict,
  inventory_id uuid references public.inventory(id) on delete set null,
  colour_code text not null,
  colour_name text not null,
  quantity integer not null check (quantity > 0),
  rate numeric(12,2) not null check (rate > 0),
  line_total numeric(12,2) generated always as (round(quantity * rate, 2)) stored,
  created_at timestamptz not null default now()
);

alter table public.stock_movements add column if not exists sale_id uuid references public.sales(id) on delete set null;
create index if not exists sales_created_at_idx on public.sales(created_at desc);
create index if not exists sale_items_sale_id_idx on public.sale_items(sale_id);
create index if not exists stock_movements_sale_id_idx on public.stock_movements(sale_id);

alter table public.sales enable row level security;
alter table public.sale_items enable row level security;
alter table public.sale_payments enable row level security;

drop policy if exists "Authorized users read sales" on public.sales;
create policy "Authorized users read sales" on public.sales for select to authenticated using (public.is_authorized_stock_user());
drop policy if exists "Authorized users read sale items" on public.sale_items;
create policy "Authorized users read sale items" on public.sale_items for select to authenticated using (public.is_authorized_stock_user());
drop policy if exists "Authorized users read sale payments" on public.sale_payments;
create policy "Authorized users read sale payments" on public.sale_payments for select to authenticated using (public.is_authorized_stock_user());

create or replace function public.create_sale(
  p_customer_name text,
  p_customer_phone text,
  p_items jsonb,
  p_amount_received numeric default 0
) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_sale_id uuid;
  v_total numeric(12,2) := 0;
  v_received numeric(12,2) := coalesce(p_amount_received,0);
  v_item jsonb;
  v_inventory public.inventory%rowtype;
  v_qty integer;
  v_rate numeric(12,2);
  v_count integer := 0;
begin
  if auth.uid() is null or not public.is_authorized_stock_user() then
    raise exception 'You are not authorized to manage this inventory.';
  end if;
  if length(trim(coalesce(p_customer_name,''))) = 0 or length(trim(coalesce(p_customer_phone,''))) = 0 then
    raise exception 'Customer name and mobile number are required.';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Add at least one item to the sale.';
  end if;
  if jsonb_array_length(p_items) > 100 then raise exception 'A sale can contain at most 100 line items.'; end if;

  -- Validate each line and reject duplicate inventory IDs.
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_count := v_count + 1;
    if (v_item->>'inventory_id') is null then raise exception 'An item is missing its inventory reference.'; end if;
    if exists (
      select 1 from jsonb_array_elements(p_items) x
      where x->>'inventory_id' = v_item->>'inventory_id'
      group by x->>'inventory_id' having count(*) > 1
    ) then raise exception 'The same colour appears more than once. Combine its quantity.'; end if;
    v_qty := (v_item->>'quantity')::integer;
    v_rate := (v_item->>'rate')::numeric;
    if v_qty <= 0 or v_rate <= 0 then raise exception 'Quantity and rate must be greater than zero.'; end if;
    v_total := v_total + round(v_qty * v_rate,2);
  end loop;
  if v_received < 0 or v_received > v_total then raise exception 'Amount received cannot exceed the sale total.'; end if;

  -- Lock all selected stock rows in stable order, then validate availability.
  perform 1 from public.inventory i
    where i.id in (select (x->>'inventory_id')::uuid from jsonb_array_elements(p_items) x)
    order by i.id for update;
  if (select count(*) from public.inventory i where i.id in (select (x->>'inventory_id')::uuid from jsonb_array_elements(p_items) x)) <> v_count then
    raise exception 'One or more selected colours no longer exist. Refresh inventory.';
  end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_inventory from public.inventory where id=(v_item->>'inventory_id')::uuid;
    if v_inventory.quantity < v_qty then
      raise exception 'Insufficient stock for % (%). Available: %, requested: %.', v_inventory.colour_name, v_inventory.colour_code, v_inventory.quantity, v_qty;
    end if;
  end loop;

  insert into public.sales(customer_name,customer_phone,subtotal,amount_received,payment_status,created_by)
  values(trim(p_customer_name),trim(p_customer_phone),v_total,v_received,
    case when v_received = 0 then 'unpaid' when v_received = v_total then 'paid' else 'partial' end,auth.uid())
  returning id into v_sale_id;
  if v_received > 0 then
    insert into public.sale_payments(sale_id,amount,recorded_by) values(v_sale_id,v_received,auth.uid());
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    v_rate := (v_item->>'rate')::numeric;
    select * into v_inventory from public.inventory where id=(v_item->>'inventory_id')::uuid;
    insert into public.sale_items(sale_id,inventory_id,colour_code,colour_name,quantity,rate)
    values(v_sale_id,v_inventory.id,v_inventory.colour_code,v_inventory.colour_name,v_qty,v_rate);
    update public.inventory set quantity=quantity-v_qty,updated_at=now() where id=v_inventory.id;
    insert into public.stock_movements(inventory_id,colour_code,colour_name,movement_type,quantity,reason,created_by,sale_id)
    values(v_inventory.id,v_inventory.colour_code,v_inventory.colour_name,'out',v_qty,'Sale #'||v_sale_id::text,auth.uid(),v_sale_id);
  end loop;
  return v_sale_id;
end;
$$;
revoke all on function public.create_sale(text,text,jsonb,numeric) from public;
grant execute on function public.create_sale(text,text,jsonb,numeric) to authenticated;

create or replace function public.add_sale_payment(p_sale_id uuid,p_amount numeric)
returns void language plpgsql security definer set search_path = '' as $$
declare v_sale public.sales%rowtype; v_new numeric(12,2);
begin
  if auth.uid() is null or not public.is_authorized_stock_user() then raise exception 'You are not authorized.'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Payment must be greater than zero.'; end if;
  select * into v_sale from public.sales where id=p_sale_id for update;
  if not found or v_sale.status <> 'completed' then raise exception 'Only completed sales can receive payments.'; end if;
  v_new := v_sale.amount_received + p_amount;
  if v_new > v_sale.subtotal then raise exception 'Payment exceeds the outstanding balance of %.',v_sale.subtotal-v_sale.amount_received; end if;
  insert into public.sale_payments(sale_id,amount,recorded_by) values(p_sale_id,p_amount,auth.uid());
  update public.sales set amount_received=v_new,
    payment_status=case when v_new=0 then 'unpaid' when v_new=subtotal then 'paid' else 'partial' end
  where id=p_sale_id;
end;
$$;
revoke all on function public.add_sale_payment(uuid,numeric) from public;
grant execute on function public.add_sale_payment(uuid,numeric) to authenticated;

create or replace function public.cancel_sale(p_sale_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare v_sale public.sales%rowtype; v_line public.sale_items%rowtype;
begin
  if auth.uid() is null or not public.is_authorized_stock_user() then raise exception 'You are not authorized.'; end if;
  select * into v_sale from public.sales where id=p_sale_id for update;
  if not found then raise exception 'Sale not found.'; end if;
  if v_sale.status <> 'completed' then raise exception 'This sale has already been cancelled.'; end if;
  -- Lock all surviving inventory rows before restoring stock.
  perform 1 from public.inventory i join public.sale_items si on si.inventory_id=i.id
    where si.sale_id=p_sale_id order by i.id for update of i;
  for v_line in select * from public.sale_items where sale_id=p_sale_id order by id loop
    if v_line.inventory_id is null then raise exception 'Cannot restore stock because an inventory item was deleted.'; end if;
    update public.inventory set quantity=quantity+v_line.quantity,updated_at=now() where id=v_line.inventory_id;
    insert into public.stock_movements(inventory_id,colour_code,colour_name,movement_type,quantity,reason,created_by,sale_id)
    values(v_line.inventory_id,v_line.colour_code,v_line.colour_name,'in',v_line.quantity,'Cancellation of sale #'||v_sale.sale_number,auth.uid(),p_sale_id);
  end loop;
  update public.sales set status='cancelled',payment_status='cancelled',cancelled_at=now(),cancelled_by=auth.uid() where id=p_sale_id;
end;
$$;
revoke all on function public.cancel_sale(uuid) from public;
grant execute on function public.cancel_sale(uuid) to authenticated;
